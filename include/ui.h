/* A sign stands only once on a pair of screens. The top screen tells the motif (ui_motif) of every sign it
 * draws in the card's head (ui_detail) and in its footer line (ui_foot, ui_foot_warn), whatever its size, into
 * ui_top_signs (ui_begin clears it; a gallery, the carousel and the empty placeholder tell none); it is drawn before
 * the bottom screen. The note under it shows its sign (ART_INFO_*) only if its motif is not among them, else it goes
 * without it: ui_popup_draw takes the sign through ui_sign_once (the box has none). A note's sign is the
 * warning or the SD card, so the warning is the one motif (the folder's and the house's served only the box). The
 * bottom screen's own controls (the corner button's folder) are not signs here. */
static inline unsigned ui_motif(int sprite)
{
    return sprite == ART_WARN || sprite == ART_WARN_FOOT || sprite == ART_INFO_WARN;
}
extern unsigned ui_top_signs;
static inline int ui_sign_once(int sign)
{
    return sign >= 0 && (ui_motif(sign) & ui_top_signs) ? -1 : sign;
}

