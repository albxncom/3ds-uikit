"""art_names.py UI_ART_H OUT_H: the names in a generated ui_art.h as C strings, for a recorder's names: the
sprites' (the kit's atlas and sheet, then the application's part's of part_art.h beside it when there is one, ART_NAME[] by id), the selection corners' (ART_CORNER_NAME), the colours'
(ART_COLOUR_NAME), the schemes' (ART_SCHEME_NAME), and two lists as X macros: the looks built (ART_LOOKS: the
look_art and its name) and the looks' own blobs (ART_BLOBS: the tables, the look, the blob's name, how many per
scheme). Each name is the id's without "ART_"."""
import re
import sys
from pathlib import Path

text = open(sys.argv[1], encoding="utf-8").read()
PART_H = Path(sys.argv[1]).parent / "part_art.h"      # none beside a kit-only ui_art.h (the example's walk)
part = PART_H.read_text(encoding="utf-8") if PART_H.is_file() else None


def enum(name, last, source=None):
    m = re.search(r"enum %s \{\n(.*?),\n    %s\n\};" % (name, last), source or text, re.S) if last else \
        re.search(r"enum %s \{\n(.*?)\n\};" % name, source or text, re.S)
    if not m:
        raise SystemExit("art_names: no enum %s in %s" % (name, sys.argv[1]))
    return [re.match(r"\s*ART_(\w+)", line).group(1) for line in m.group(1).split(",\n")]


def strings(c_name, size, names):
    return "__attribute__((unused)) static const char *const %s[%s] = {\n%s\n};\n" % (
        c_name, size, ",\n".join('    "%s"' % n for n in names))


looks = re.findall(r"^extern const look_art ART_(\w+);", text, re.M)
blobs = []
for name, n in re.findall(r"^extern const uint8_t \*const ART_(\w+)_Z\[ART_SCHEMES\]\[(\d+)\];", text, re.M):
    look = next(lk for lk in looks if name.startswith(lk + "_"))
    blobs.append('X(ART_%s_Z, ART_%s_Z_SIZE, "%s", "%s", %s)' % (name, name, look.lower(), name[len(look) + 1:], n))
scheme_names = [n[len("SCHEME_"):] for n in enum("art_scheme", "ART_SCHEMES")]
open(sys.argv[2], "w", encoding="utf-8").write(
    "/* Generated by tools/flows/art_names.py from ui_art.h; do not edit. */\n" +
    strings("ART_NAME", "", enum("art_id", "ART_COUNT") + enum("art_glass_id", "ART_ALL") +
            (enum("part_art_id", None, part) if part else [])) +
    strings("ART_CORNER_NAME", "ART_CORNER_COUNT", enum("art_corner_id", "ART_CORNER_COUNT")) +
    strings("ART_COLOUR_NAME", "ART_COLOURS", enum("art_colour", "ART_COLOURS")) +
    strings("ART_SCHEME_NAME", "ART_SCHEMES", scheme_names) +
    "#define ART_LOOKS(X) %s\n" % " ".join('X(ART_%s, "%s")' % (lk, lk.lower()) for lk in looks) +
    "#define ART_BLOBS(X) %s\n" % " ".join(blobs))
